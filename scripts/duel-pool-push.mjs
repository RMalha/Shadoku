// The 1v1's board pool: writes the SQL that loads engine/puzzles_duel into the table `duel_pool` (migrations/0008_app_duel.sql;
// architecture 4.20). A match deals one 5 x 5, one 6 x 6 and one 7 x 7 from it. Each case file becomes one row: the player's
// copy of the case WITHOUT its answer, walkthrough, hints or Puzzle ID, the answer and the solver's order of placements in
// their own columns, which no endpoint ever sends (functions/_lib/app/duel_rules.js poolRow does the split, and stops at any
// field it does not know).
//
//   node scripts/duel-pool-push.mjs                               writes .wrangler/duel_pool.sql
//   node scripts/duel-pool-push.mjs --dir some/folder --out some/file.sql
//   node scripts/duel-pool-push.mjs --retire id1,id2              also switches those boards off (they are never deleted)
//   npx wrangler d1 execute shadoku --local --file .wrangler/duel_pool.sql                       (local dev)
//   npx wrangler d1 execute shadoku-test --remote --env preview --file .wrangler/duel_pool.sql   (the test server)
//   npx wrangler d1 execute shadoku --remote --file .wrangler/duel_pool.sql                      (production)
//
// A board is immutable: pushing it again changes nothing (a board switched off comes back on), and a file that changed under
// the same id is NOT loaded over the old one: give it a new id and retire the old. Refused, with the reason, and then nothing
// is written: a case that is not a square 5 x 5, 6 x 6 or 7 x 7, a Story case, lesson board, daily or multi-assassin case, a
// case whose uniqueness gate (G3) is not true, a case the app, the site or the book already holds with its answer, a field
// duel_rules.js does not know.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { poolRow, DUEL } from "../functions/_lib/app/duel_rules.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENGINE = path.join(ROOT, "engine");
/** One SQL statement may be 100 KB in D1; a 7 x 7 row is about 15 KB. */
const MAX_STATEMENT = 90000;
/** Folders whose cases are public with their answers (the app's bundle, the site, the dailies' feed, the printed book). */
const PUBLIC_DIRS = ["puzzles", "puzzles_multi", "puzzles_app", "puzzles_daily", "daily_queue", "puzzles_book"];

const jsonFiles = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => path.join(dir, f)) : []);
const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
/** JSON in plain ASCII (every other character escaped), so the SQL file means the same in any console or code page. */
const ascii = (v) => JSON.stringify(v).replace(/[\u007f-￿]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`);

/** → the Puzzle IDs and case ids of every case that is public somewhere. */
function publicCases(engine) {
  const out = new Set();
  for (const dir of PUBLIC_DIRS) {
    for (const f of jsonFiles(path.join(engine, dir))) {
      try { const c = JSON.parse(fs.readFileSync(f, "utf8")); for (const k of [c.id, c.puzzleId]) if (typeof k === "string" && k) out.add(k); } catch { /* not a case file */ }
    }
  }
  return out;
}

/** → { rows: [{ id, size, difficulty, people, body, solution, walk, sha256 }], refused: ["<file>: <why>"] } for a folder of case files. */
export function poolRows(dir, { engine = ENGINE } = {}) {
  const taken = publicCases(engine), rows = [], refused = [], ids = new Set();
  for (const file of jsonFiles(dir)) {
    const name = path.basename(file);
    try {
      const raw = fs.readFileSync(file), c = JSON.parse(raw.toString("utf8"));
      const row = poolRow(c);
      if (!c.gates || c.gates.G3_unique_full !== true) throw new Error("duel pool: its uniqueness gate (G3_unique_full) is not true: run --verify on it");
      if (ids.has(row.id)) throw new Error(`duel pool: the id ${row.id} appears twice`);
      for (const k of [c.id, c.puzzleId]) if (typeof k === "string" && taken.has(k)) throw new Error(`duel pool: ${k} is already in a folder whose answers are public (${PUBLIC_DIRS.join(", ")})`);
      ids.add(row.id);
      rows.push({ ...row, sha256: crypto.createHash("sha256").update(raw).digest("hex") });
    } catch (e) {
      refused.push(`${name}: ${String((e && e.message) || e).replace(/^duel pool: /, "")}`);
    }
  }
  return { rows, refused };
}

/** → the SQL for those rows. `now`: when they were added; `retire`: ids to switch off. */
export function poolSql(rows, { now = Date.now(), retire = [] } = {}) {
  const lines = ["-- generated by scripts/duel-pool-push.mjs: do not edit"];
  for (const r of rows) {
    const sql = `INSERT INTO duel_pool (id, size, difficulty, people, body, solution, walk, sha256, added, active) VALUES (${quote(r.id)}, ${r.size}, ${quote(r.difficulty)}, ${r.people}, `
      + `${quote(ascii(r.body))}, ${quote(ascii(r.solution))}, ${quote(ascii(r.walk))}, ${quote(r.sha256)}, ${now}, 1) `
      + "ON CONFLICT (id) DO UPDATE SET active = 1 WHERE duel_pool.sha256 = excluded.sha256;";
    if (sql.length > MAX_STATEMENT) throw new Error(`duel pool: ${r.id} makes a statement of ${sql.length} bytes (D1 takes 100 KB)`);
    lines.push(sql);
  }
  for (const id of retire) lines.push(`UPDATE duel_pool SET active = 0 WHERE id = ${quote(id)};`);
  return lines.join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : null; };
  const dir = path.resolve(arg("--dir") || path.join(ENGINE, "puzzles_duel"));
  const out = path.resolve(arg("--out") || path.join(ROOT, ".wrangler", "duel_pool.sql"));
  const retire = (arg("--retire") || "").split(",").map((s) => s.trim()).filter(Boolean);
  if (!fs.existsSync(dir)) { console.error(`[duel-pool] ${path.relative(ROOT, dir)} does not exist: the puzzle-maker fills it with fresh 5 x 5, 6 x 6 and 7 x 7 boards`); process.exit(1); }
  const { rows, refused } = poolRows(dir);
  if (refused.length) {
    console.error(`[duel-pool] ${refused.length} file(s) refused, nothing written:`);
    for (const r of refused) console.error(`  ${r}`);
    process.exit(1);
  }
  if (!rows.length && !retire.length) { console.error(`[duel-pool] no case files in ${path.relative(ROOT, dir)}`); process.exit(1); }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, poolSql(rows, { retire }), "utf8");
  const count = (size) => rows.filter((r) => r.size === size).length;
  console.log(`[duel-pool] ${rows.length} boards (${DUEL.sizes.map((s) => `${count(s)} of ${s} x ${s}`).join(", ")})${retire.length ? `, ${retire.length} retired` : ""} -> ${path.relative(ROOT, out)}`);
  for (const s of DUEL.sizes) if (!count(s)) console.log(`[duel-pool] WARNING: no ${s} x ${s} board in this push: a match needs one of each size in the pool`);
}
